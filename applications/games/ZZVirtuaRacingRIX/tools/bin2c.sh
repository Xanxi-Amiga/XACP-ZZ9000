#!/bin/bash
# bin2c.sh - same output as tools/bin2c.c, without a host C compiler
# (needs od and awk, both present in MSYS2).
#   bash tools/bin2c.sh  bin/zzvr_a3a.bin  amiga/blob_data.c
#   bash tools/bin2c.sh  amiga/icons/ZZVirtuaRacingRIX.info  amiga/icon_data.c  g_icon
set -e
in="$1"; out="$2"; sym="${3:-g_blob}"   # 1.0: optional symbol prefix (g_icon for the icon)
if [ -z "$in" ] || [ -z "$out" ]; then echo "usage: $0 input.bin output.c" >&2; exit 2; fi
[ -s "$in" ] || { echo "cannot open $in (or empty)" >&2; exit 1; }
n=$(wc -c < "$in" | tr -d ' ')
{
  printf '/* %s - %s embedded in the ZZVirtuaRacingRIX executable.\n' "$(basename "$out")" "$sym"
  printf ' * Generated by tools/bin2c from %s - do not edit.\n' "$in"
  printf ' */\n'
  printf 'const unsigned long %s_size = %sUL;\n' "$sym" "$n"
  printf 'const unsigned char %s_data[%s] = {\n' "$sym" "$n"
  od -An -v -tx1 "$in" | awk '{ for(i=1;i<=NF;i++){ printf "0x%s,", $i; c++; if(c%24==0) printf "\n" } } END { if(c%24) printf "\n" }'
  printf '};\n'
} > "$out"
echo "bin2c: wrote $out ($n bytes)" >&2
