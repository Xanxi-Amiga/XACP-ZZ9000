"""Derive the slot order and signatures directly from the pinned MiniGL 29.1 ABI."""
from pathlib import Path
import re
def generate(root):
    header=(root/'vendor/minigl/minigl_dispatch.h').read_text()
    body=header.split('typedef struct MGLDispatchTable {',1)[1].split('} MGLDispatchTable;',1)[0]
    body=re.sub(r'/\*.*?\*/','',body,flags=re.S)
    slots=re.findall(r'^\s*([\w\s*]+?)\s*\(\*(\w+)\)\((.*?)\);',body,re.M)
    assert len(slots)==205 and '#define MINIGL_DISPATCH_ABI_VERSION 5UL' in header
    impl=(root/'src68k/front.c').read_text()
    defined=set(re.findall(r'\bimpl_(\w+)\s*\(',impl))
    defs=(root/'src68k/abi_types.h').read_text()
    out=['/* Derived from vendor/minigl/minigl_dispatch.h. See its license. */',defs,
         'typedef struct ZZDispatch {'+body+'} ZZDispatch;',
         'typedef char zz_dispatch_840[sizeof(ZZDispatch)==840?1:-1];',
         'extern const ZZDispatch zz_dispatch;']
    stubs=['#include "abi.h"','#include "os.h"','#include "blackbox.h"','extern void zz_missing(unsigned int);','extern GLcontext zz_current;',
           '/* A8 call trace: one counter per slot, the slot names for the report */',
           'Z zz_calls[205];','Z zz_last_slot;   /* A8.3: the slot entered last (heartbeat) */',
           '/* A8.4: every call is also written to the black box of an armed context (entered, returned) */',
           'volatile unsigned short *zz_bb;','unsigned int zz_bb_seq;']
    names=['/* Generated by tools/dispatch.py: the MiniGL 29.1 slot names (library trace, ZZMiniGLLoad black box). */',
           'const char *const zz_slot_names[205]={'+','.join('"'+n+'"' for _,n,_ in slots)+'};']
    table=[];rows=[]
    def wrap(prefix,ret,name,args,idx):
        def argname(a):
            m=re.search(r'\(\s*\*\s*(\w+)\s*\)',a)          # function pointer: void (*func)(void)
            return m.group(1) if m else a.strip().split()[-1].lstrip('*').split('[')[0]
        actual=[argname(arg) for arg in re.split(r',(?![^()]*\))',args) if arg.strip()!='void']
        call='body_'+name+'('+', '.join(actual)+')'
        if ret=='void':
            return f'static void {prefix}{name}({args}) {{ Z bb_s; zz_calls[{idx}]++; zz_last_slot={idx}; ZZ_BB_IN({idx}u,bb_s); {call}; ZZ_BB_OUT({idx}u,bb_s); }}'
        return f'static {ret} {prefix}{name}({args}) {{ Z bb_s; {ret} bb_r; zz_calls[{idx}]++; zz_last_slot={idx}; ZZ_BB_IN({idx}u,bb_s); bb_r={call}; ZZ_BB_OUT({idx}u,bb_s); return bb_r; }}'
    for idx,(ret,name,args) in enumerate(slots):
        ret=ret.strip()
        if name in defined:
            out.append(f'{ret} impl_{name}({args});')
            if name.startswith('GL') or name=='MGLSwitchDisplay':
                actual=[arg.strip().split()[-1].lstrip('*') for arg in args.split(',') if arg.strip()!='void']
                expr='impl_'+name+'('+', '.join(actual)+')'
                group=0 if name in ('GLFlush','GLFinish','MGLSwitchDisplay','GLGetError','GLGetString') else 2 if name.startswith('GLVertex') else 3 if name=='GLBindTexture' else 4 if name in ('GLTexImage2D','GLTexSubImage2D') else 1
                result='' if ret=='void' else ret+' result;'
                early=expr+';return;' if ret=='void' else 'return '+expr+';'
                invoke=expr+';' if ret=='void' else 'result='+expr+';'
                done='' if ret=='void' else 'return result;'
                stubs.append(f'static inline {ret} body_{name}({args}) {{ Z start_tick,io; {result} if(!zz_profile){{{early}}} start_tick=zz_clock();io=zz_transfer_ticks();{invoke} zz_profile_add(start_tick,io,{group});{done} }}')
                stubs.append(wrap('timed_',ret,name,args,idx))
                table.append('timed_'+name)
            else:
                actual=[arg.strip().split()[-1].lstrip('*') for arg in args.split(',') if arg.strip()!='void']
                expr='impl_'+name+'('+', '.join(actual)+')'
                body=expr+';' if ret=='void' else 'return '+expr+';'
                stubs.append(f'static inline {ret} body_{name}({args}) {{ {body} }}')
                stubs.append(wrap('counted_',ret,name,args,idx))
                table.append('counted_'+name)
        else:
            result='' if ret=='void' else ' return 0;'
            stubs.append(f'static inline {ret} body_{name}({args}) {{ zz_missing({idx+1});{result} }}')
            stubs.append(wrap('missing_',ret,name,args,idx))
            table.append('missing_'+name)
        rows.append(f'{idx+1:3} {20+4*idx:3} {name} {"implemented" if name in defined else "unsupported"}')
    stubs+=['const ZZDispatch zz_dispatch = {5, sizeof(ZZDispatch), 2, 0, &zz_current,',',\n'.join(table),'};']
    (root/'build/abi.h').write_text('\n'.join(out)+'\n')
    (root/'build/dispatch.c').write_text('\n'.join(stubs)+'\n')
    (root/'build/slot_names.c').write_text('\n'.join(names)+'\n')
    (root/'build/slots.txt').write_text('\n'.join(rows)+'\n')
    return slots
