#!/usr/bin/env python3
"""bin2c.py - embeds the ARM Core1 blob in a C array for the 68k launcher.
Same output as tools/bin2c.c / tools/bin2c.sh (g_blob_size + g_blob_data[N]).
Usage: python tools/bin2c.py input.bin output.c
"""
import sys
from pathlib import Path

def main(argv):
    if len(argv) != 3:
        sys.stderr.write("usage: %s input.bin output.c\n" % argv[0])
        return 2
    src, dst = Path(argv[1]), Path(argv[2])
    data = src.read_bytes()
    if not data:
        sys.stderr.write("empty/invalid input\n")
        return 1
    n = len(data)
    out = []
    out.append("/* blob_data.c - ARM Core1 blob embedded in the ZZPicoDriveSMS executable.\n")
    out.append(" * Generated by tools/bin2c from %s - do not edit.\n" % argv[1])
    out.append(" */\n")
    out.append("const unsigned long g_blob_size = %dUL;\n" % n)
    out.append("const unsigned char g_blob_data[%d] = {\n" % n)
    for i in range(0, n, 24):
        out.append("".join("0x%02x," % b for b in data[i:i + 24]) + "\n")
    out.append("};\n")
    dst.write_bytes("".join(out).encode("ascii"))
    sys.stderr.write("bin2c: wrote %s (%d bytes)\n" % (argv[2], n))
    return 0

if __name__ == "__main__":
    sys.exit(main(sys.argv))
