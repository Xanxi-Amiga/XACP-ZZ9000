# embed_blob.py - ZZGear RasterIX C1: Core1 binary -> C array for the 68k launcher
import sys, hashlib
from pathlib import Path
src, dst = Path(sys.argv[1]), Path(sys.argv[2])
b = src.read_bytes()
if not b or len(b) > 0x1F0000:
    raise SystemExit('ERROR: Core1 blob size %d' % len(b))
with dst.open('w', newline='\n') as f:
    f.write('/* generated by tools/embed_blob.py from %s (%d bytes, sha256 %s) */\n' % (src.name, len(b), hashlib.sha256(b).hexdigest()))
    f.write('#include <exec/types.h>\nconst UBYTE zzgear_core1_blob[]={\n')
    for i, x in enumerate(b):
        f.write('0x%02x,' % x)
        if (i + 1) % 16 == 0:
            f.write('\n')
    f.write('\n};\nconst ULONG zzgear_core1_blob_size=sizeof(zzgear_core1_blob);\n')
print('embedded %d bytes' % len(b))
